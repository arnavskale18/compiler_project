# Sample 1: Arithmetic Expressions & Precedence
x = 10 + 5 * 2
y = (10 + 5) * 2
z = 15 // 4
rem = 15 % 4
div = 10 / 4
greeting = "Hello" + " " + "World"

print("x (should be 20):", x)
print("y (should be 30):", y)
print("z (floor div 15 // 4 = 3):", z)
print("rem (15 % 4 = 3):", rem)
print("div (10 / 4 = 2.5):", div)
print("greeting:", greeting)
