"""C++17 Target Code Generator for CodeX.

Translates a semantically-validated AST into clean, idiomatic, and valid C++17.
Handles type conversions, Python-compatible print semantics, floor division,
and standard library headers.
"""

from typing import Set, Dict, List, Optional
from .ast_nodes import (
    Program,
    Statement,
    AssignStmt,
    PrintStmt,
    PassStmt,
    IfStmt,
    WhileStmt,
    Expression,
    BinaryOp,
    UnaryOp,
    Literal,
    Identifier,
)
from .symbol_table import SymbolTable


TYPE_MAP: Dict[str, str] = {
    "int": "int64_t",
    "float": "double",
    "bool": "bool",
    "string": "std::string",
}


class CppCodeGenerator:
    def __init__(self, symbol_table: SymbolTable):
        self.symbol_table = symbol_table
        self.declared_vars: Set[str] = set()
        self.indent_level = 1

    def indent_str(self) -> str:
        return "    " * self.indent_level

    def generate(self, program: Program) -> str:
        self.declared_vars = set()
        self.indent_level = 1

        var_decls = []
        declared_names = set()
        for sym in self.symbol_table.get_all_symbols():
            if sym.name not in declared_names:
                declared_names.add(sym.name)
                cpp_type = TYPE_MAP.get(sym.type_name, "auto")
                default_init = {
                    "int": " = 0",
                    "float": " = 0.0",
                    "bool": " = false",
                    "string": ' = ""',
                }.get(sym.type_name, "")
                var_decls.append(f"    {cpp_type} {sym.name}{default_init};")

        var_decl_code = "\n".join(var_decls)
        if var_decl_code:
            var_decl_code += "\n"

        body_lines: List[str] = []
        for stmt in program.statements:
            body_lines.append(self.generate_statement(stmt))

        body_code = "\n".join(line for line in body_lines if line.strip())

        full_code = f"""// Generated by CodeX Compiler (Python-subset to C++17)
#include <iostream>
#include <string>
#include <cmath>
#include <cstdint>

// Runtime helper for Python-like boolean, float, and string output
template <typename T>
void _codex_print_item(const T& val) {{
    if constexpr (std::is_same_v<T, bool>) {{
        std::cout << (val ? "True" : "False");
    }} else if constexpr (std::is_same_v<T, double> || std::is_same_v<T, float>) {{
        if (std::floor(val) == val && !std::isinf(val) && !std::isnan(val)) {{
            std::cout << static_cast<int64_t>(val) << ".0";
        }} else {{
            std::cout << val;
        }}
    }} else {{
        std::cout << val;
    }}
}}

// Runtime helper for Python-compatible floor division
inline int64_t _codex_floordiv(int64_t a, int64_t b) {{
    int64_t res = a / b;
    int64_t rem = a % b;
    if ((rem != 0) && ((a < 0) ^ (b < 0))) {{
        res -= 1;
    }}
    return res;
}}

// Runtime helper for Python-compatible modulo
inline int64_t _codex_mod(int64_t a, int64_t b) {{
    int64_t rem = a % b;
    if ((rem != 0) && ((a < 0) ^ (b < 0))) {{
        rem += b;
    }}
    return rem;
}}

int main() {{
{var_decl_code}{body_code}
    return 0;
}}
"""
        return full_code

    def generate_statement(self, stmt: Statement) -> str:
        if isinstance(stmt, AssignStmt):
            var_name = stmt.target.name
            val_code = self.generate_expr(stmt.value)
            return f"{self.indent_str()}{var_name} = {val_code};"

        elif isinstance(stmt, PrintStmt):
            if not stmt.expressions:
                return f"{self.indent_str()}std::cout << std::endl;"

            parts: List[str] = []
            for i, expr in enumerate(stmt.expressions):
                expr_code = self.generate_expr(expr)
                parts.append(f"_codex_print_item({expr_code});")
                if i < len(stmt.expressions) - 1:
                    parts.append('std::cout << " ";')
            parts.append("std::cout << std::endl;")

            # Combine print calls into a neat single statement or block
            return f"{self.indent_str()}" + f" ".join(parts)

        elif isinstance(stmt, PassStmt):
            return f"{self.indent_str()}/* pass */;"

        elif isinstance(stmt, IfStmt):
            return self.generate_if_stmt(stmt)

        elif isinstance(stmt, WhileStmt):
            return self.generate_while_stmt(stmt)

        return f"{self.indent_str()}// Unsupported statement: {type(stmt).__name__}"

    def generate_if_stmt(self, stmt: IfStmt) -> str:
        cond_code = self.generate_expr(stmt.condition)
        lines: List[str] = [f"{self.indent_str()}if ({cond_code}) {{"]
        
        self.indent_level += 1
        for s in stmt.then_body:
            lines.append(self.generate_statement(s))
        self.indent_level -= 1

        for elif_branch in stmt.elif_branches:
            elif_cond_code = self.generate_expr(elif_branch.condition)
            lines.append(f"{self.indent_str()}}} else if ({elif_cond_code}) {{")
            self.indent_level += 1
            for s in elif_branch.body:
                lines.append(self.generate_statement(s))
            self.indent_level -= 1

        if stmt.else_body:
            lines.append(f"{self.indent_str()}}} else {{")
            self.indent_level += 1
            for s in stmt.else_body:
                lines.append(self.generate_statement(s))
            self.indent_level -= 1

        lines.append(f"{self.indent_str()}}}")
        return "\n".join(lines)

    def generate_while_stmt(self, stmt: WhileStmt) -> str:
        cond_code = self.generate_expr(stmt.condition)
        lines: List[str] = [f"{self.indent_str()}while ({cond_code}) {{"]

        self.indent_level += 1
        for s in stmt.body:
            lines.append(self.generate_statement(s))
        self.indent_level -= 1

        lines.append(f"{self.indent_str()}}}")
        return "\n".join(lines)

    def generate_expr(self, expr: Expression) -> str:
        if isinstance(expr, Literal):
            if expr.lit_type == "bool":
                return "true" if expr.value else "false"
            elif expr.lit_type == "string":
                # Escape standard C++ string
                escaped = expr.value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
                return f'std::string("{escaped}")'
            elif expr.lit_type == "float":
                s = str(expr.value)
                return s if "." in s else f"{s}.0"
            return str(expr.value)

        elif isinstance(expr, Identifier):
            return expr.name

        elif isinstance(expr, UnaryOp):
            operand_code = self.generate_expr(expr.operand)
            if expr.op == "not":
                return f"(!{operand_code})"
            return f"({expr.op}{operand_code})"

        elif isinstance(expr, BinaryOp):
            left_code = self.generate_expr(expr.left)
            right_code = self.generate_expr(expr.right)
            op = expr.op

            if op == "//":
                return f"_codex_floordiv({left_code}, {right_code})"
            elif op == "%":
                return f"_codex_mod({left_code}, {right_code})"
            elif op == "/":
                return f"(static_cast<double>({left_code}) / static_cast<double>({right_code}))"
            elif op == "and":
                return f"({left_code} && {right_code})"
            elif op == "or":
                return f"({left_code} || {right_code})"
            else:
                return f"({left_code} {op} {right_code})"

        raise ValueError(f"Unknown expression type in C++ generator: {type(expr).__name__}")


def generate_cpp(program: Program, symbol_table: SymbolTable) -> str:
    generator = CppCodeGenerator(symbol_table)
    return generator.generate(program)
